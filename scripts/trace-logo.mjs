/**
 * Vectorises the authentic Tmi Jarkko Karilahti logo (logo.JPG from the company's
 * Webnode site, see docs/ASSET_PROVENANCE.md) into layered SVG paths, so the site
 * uses – and can animate – the real artwork instead of an invented substitute.
 *
 * Layers (original geometry, traced with potrace from a 4× Lanczos upscale):
 *   tmi        – "Tmi" (black script)
 *   jarko      – "Jar" + "ko" (black script, shares the blue K)
 *   karilahti  – "arilahti" (black script)
 *   k          – the large blue K shared by "JarKko" and "Karilahti"
 *
 * Usage: node scripts/trace-logo.mjs
 * Output: src/components/brand/logoPaths.ts, public/brand/logo.svg, public/brand/logo-light.svg
 */
import sharp from 'sharp'
import potrace from 'potrace'
import fs from 'node:fs/promises'

const SRC = 'source-assets/original/200000000-79b3e7aae8__logo.JPG'
const S = 4
const meta = await sharp(SRC).metadata()
const W = meta.width * S
const H = meta.height * S
const rgb = await sharp(SRC).removeAlpha().resize(W, H, { kernel: 'lanczos3' }).blur(2.2).raw().toBuffer()
const N = W * H

const blue = new Uint8Array(N)
const black = new Uint8Array(N)
for (let i = 0; i < N; i++) {
  const r = rgb[i * 3], g = rgb[i * 3 + 1], b = rgb[i * 3 + 2]
  const lum = 0.299 * r + 0.587 * g + 0.114 * b
  if (b - r > 70 && b - g > 70 && b > 150) blue[i] = 1
  else if (lum < 120 && !(b - r > 45)) black[i] = 1
}

// Close tiny gaps in the blue mask left by JPEG ringing around the K.
function dilateErode(mask) {
  const out = new Uint8Array(N)
  for (let y = 1; y < H - 1; y++)
    for (let x = 1; x < W - 1; x++) {
      const p = y * W + x
      out[p] = mask[p] || (mask[p - 1] && mask[p + 1]) || (mask[p - W] && mask[p + W]) ? 1 : 0
    }
  return out
}

function components(mask) {
  const lab = new Int32Array(N).fill(-1)
  const comps = []
  const stack = new Int32Array(N)
  for (let p = 0; p < N; p++) {
    if (!mask[p] || lab[p] >= 0) continue
    const id = comps.length
    let sp = 0, n = 0, sy = 0, x0 = W, x1 = 0
    stack[sp++] = p
    lab[p] = id
    while (sp) {
      const q = stack[--sp]
      n++
      const x = q % W, y = (q / W) | 0
      sy += y
      if (x < x0) x0 = x
      if (x > x1) x1 = x
      for (const nb of [x > 0 ? q - 1 : -1, x < W - 1 ? q + 1 : -1, y > 0 ? q - W : -1, y < H - 1 ? q + W : -1]) {
        if (nb >= 0 && mask[nb] && lab[nb] < 0) {
          lab[nb] = id
          stack[sp++] = nb
        }
      }
    }
    comps.push({ id, n, cy: sy / n / S, x0: x0 / S, x1: x1 / S })
  }
  return { lab, comps }
}

const { lab, comps } = components(black)
const layers = { tmi: new Uint8Array(N), jarko: new Uint8Array(N), karilahti: new Uint8Array(N) }
const pick = {}
for (const c of comps) {
  if (c.n < 40 * S) continue // JPEG specks
  pick[c.id] = c.cy < 72 ? 'tmi' : c.cy < 130 ? 'jarko' : 'karilahti'
}
for (let p = 0; p < N; p++) {
  const id = lab[p]
  if (id >= 0 && pick[id]) layers[pick[id]][p] = 1
}
layers.k = dilateErode(blue)

async function trace(mask) {
  const buf = Buffer.alloc(N)
  for (let i = 0; i < N; i++) buf[i] = mask[i] ? 0 : 255
  const png = await sharp(buf, { raw: { width: W, height: H, channels: 1 } }).png().toBuffer()
  const svg = await new Promise((res, rej) =>
    potrace.trace(png, { turdSize: 60, optTolerance: 0.35, alphaMax: 1.0, threshold: 128 }, (e, s) => (e ? rej(e) : res(s))),
  )
  const d = /d="([^"]+)"/.exec(svg)[1]
  // Scale back to 1× coordinates (viewBox = original pixel grid) and round.
  return d.replace(/-?\d+(\.\d+)?/g, (v) => String(Math.round((Number(v) / S) * 100) / 100))
}

const paths = {}
for (const k of ['tmi', 'jarko', 'karilahti', 'k']) paths[k] = await trace(layers[k])

// Crop the viewBox to the artwork (with a small margin).
const vb = { x: 8, y: 14, w: 452, h: 170 }
const BLUE = '#3434f4'

const ts = `/* Generated by scripts/trace-logo.mjs from the authentic logo – do not edit by hand. */
export const LOGO_VIEWBOX = '${vb.x} ${vb.y} ${vb.w} ${vb.h}'
export const LOGO_RATIO = ${(vb.w / vb.h).toFixed(4)}
export const LOGO_BLUE = '${BLUE}'
export const logoPaths = {
  tmi: '${paths.tmi}',
  jarko: '${paths.jarko}',
  karilahti: '${paths.karilahti}',
  k: '${paths.k}',
} as const
`
await fs.mkdir('src/components/brand', { recursive: true })
await fs.writeFile('src/components/brand/logoPaths.ts', ts)
// Same data for Node build scripts (share image, favicons).
await fs.writeFile('scripts/logo-paths.mjs', ts.replace(' as const', '').replace('/* Generated', '/* Node copy – generated'))

const svg = (ink) => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${vb.x} ${vb.y} ${vb.w} ${vb.h}" role="img" aria-label="Tmi Jarkko Karilahti">
  <path fill="${ink}" d="${paths.tmi}"/>
  <path fill="${ink}" d="${paths.jarko}"/>
  <path fill="${ink}" d="${paths.karilahti}"/>
  <path fill="${BLUE}" d="${paths.k}"/>
</svg>
`
await fs.mkdir('public/brand', { recursive: true })
await fs.writeFile('public/brand/logo.svg', svg('#0b0d10'))
await fs.writeFile('public/brand/logo-light.svg', svg('#f4f5f2'))
console.log('Traced layers:', Object.fromEntries(Object.entries(paths).map(([k, v]) => [k, v.length])))
